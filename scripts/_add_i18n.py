def escape_xml(s: str) -> str:
    """Escape the small set of characters that appear in Android string values."""
    return (s.replace("&", "&amp;")
              .replace("<", "&lt;")
              .replace(">", "&gt;"))


def insert(locale: str, translations: dict) -> int:
    path = RES / f"values-{locale}" / "strings.xml"
    if not path.exists():
        print(f"SKIP {locale}: no file at {path}")
        return 0

    text = path.read_text(encoding="utf-8")
    # Skip keys already present so the script is idempotent.
    present = set(re.findall(r'<string\s+name="([^"]+)"', text))
    lines_to_add = []
    for key, val in translations.items():
        if val is None:
            continue  # tolerate typos in the mapping
        if key in present:
            continue
        if val is None:
            continue
        lines_to_add.append(f'    <string name="{key}">{escape_xml(val)}</string>')

    if not lines_to_add:
        print(f"{locale}: no changes")
        return 0

    assert "</resources>" in text, f"{locale}: no </resources> tag"
    block = "\n".join(lines_to_add) + "\n"
    new = text.replace("</resources>", block + "</resources>", 1)
    path.write_text(new, encoding="utf-8")
    print(f"{locale}: added {len(lines_to_add)} keys")
    return len(lines_to_add)


def main() -> int:
    total = 0
    for locale, translations in NEW_STRINGS.items():
        total += insert(locale, translations)
    print(f"\nTotal keys inserted: {total}")
    return 0


